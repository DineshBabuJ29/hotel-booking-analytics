"""
Run the whole project end to end and write outputs/INSIGHTS_REPORT.md.

    python python/run_all.py

Every number in the report is computed in this run. Nothing is typed in by hand.
"""
import json
import time

import config as C
import s01_clean_transform
import s02_build_database
import s03_eda
import s04_cancellation_model
import s05_demand_forecast
import s06_excel_whatif

STEPS = [("1/6 Clean & transform", s01_clean_transform), ("2/6 SQL database + queries", s02_build_database),
         ("3/6 EDA & charts", s03_eda), ("4/6 Cancellation model", s04_cancellation_model),
         ("5/6 Demand forecast", s05_demand_forecast), ("6/6 Excel what-if model", s06_excel_whatif)]


def eur(x):
    return f"€{x / 1e6:,.2f}M" if abs(x) >= 1e6 else f"€{x:,.0f}"


def write_report(m: dict) -> None:
    iss = m["cleaning_issues"]
    text = f"""# Hotel Booking Demand: Insights Report

*Generated by `python/run_all.py` from {m['raw_rows']:,} bookings at two Portuguese hotels (a City hotel and a
Resort hotel), arrivals {m['first_arrival']} to {m['last_arrival']}. Currency assumed EUR.*

## 1. Snapshot
| KPI | Value |
|---|---|
| Bookings analysed (after cleaning) | {m['clean_rows']:,} |
| Cancellation rate | {m['cancel_rate_pct']}% (City {m['city_cancel_rate_pct']}%, Resort {m['resort_cancel_rate_pct']}%) |
| Realized room revenue | {eur(m['realized_revenue'])} |
| Revenue lost to cancellations | {eur(m['lost_revenue'])} ({m['lost_share_pct']}% of booked value) |
| Realized ADR (price per room-night) | €{m['realized_adr']} (City €{m['city_realized_adr']}, Resort €{m['resort_realized_adr']}) |
| Average stay | City {m['city_avg_stay']} nights, Resort {m['resort_avg_stay']} nights |

## 2. Key findings

**1. Online travel agencies are the biggest channel, and the leakiest.** OTAs (Booking.com, Expedia, ...)
bring {m['ota_booking_share_pct']}% of bookings and {m['ota_revenue_share_pct']}% of realized revenue, but
{m['ota_cancel_pct']}% of OTA bookings cancel, so the hotels keep only {m['ota_kept_pct']}% of the value
booked through them. Direct bookings cancel {m['direct_cancel_pct']}% of the time and keep {m['direct_kept_pct']}%.
The online share of bookings grew from {m['online_share_first_q_pct']}% (first quarter of data) to
{m['online_share_last_q_pct']}% (last quarter), so the problem is growing.

**2. Cancellations cost {eur(m['lost_revenue'])}.** That is {m['lost_share_pct']}% of everything booked.
Cancellation risk rises with lead time: {m['cancel_lead_0_7_pct']}% for bookings made within a week of arrival vs
{m['cancel_lead_181_365_pct']}% for bookings made 6-12 months ahead. Group bookings cancel {m['groups_cancel_pct']}% of the time.

**3. Engaged guests cancel less.** On No-Deposit bookings, guests with at least one special request cancel
{m['cancel_with_requests_pct']}% of the time vs {m['cancel_no_requests_pct']}% without. Repeat guests cancel
{m['cancel_repeat_pct']}% vs {m['cancel_new_pct']}% for new guests.

**4. A model can flag risky bookings at the moment of booking.** Gradient boosting trained on arrivals before
Mar-2017 and tested on Mar-Aug 2017 (months it never saw) reaches ROC-AUC {m['gbm_roc_auc']} (logistic regression
{m['logit_roc_auc']}). On No-Deposit bookings, the 10% it scores riskiest cancel {m['top_decile_cancel_pct']}% of
the time vs {m['nodeposit_avg_cancel_pct']}% on average, and hold {m['top_decile_share_of_cancellations_pct']}% of all
cancellations (top 20%: {m['top2_deciles_share_of_cancellations_pct']}%). Strongest drivers:
{', '.join(m['top_features'])}.

**5. A targeted deposit policy pays.** Asking only the riskiest 10% of No-Deposit bookings for a one-night deposit
would have secured {eur(m['policy_protected_first_night'])} in the 6 test months. Even if
{m['policy_walkaway_assumption_pct']:.0f}% of those guests booked elsewhere instead (cost
{eur(m['policy_friction_cost'])}), the net effect is about **{eur(m['policy_net'])}**. Adjust the assumptions in
`excel/Hotel_Revenue_WhatIf.xlsx`.

**6. Small, safe overbooking adds revenue.** Of City-hotel bookings still on the books 3 days before arrival,
{100 * (1 - m['overbook_show_prob']):.1f}% cancel late or do not show. For a 100-room night, overbooking by
**{m['overbook_best_x']} rooms** maximises expected revenue (+{eur(m['overbook_gain_per_night'])} per night, assuming a
walked guest costs 2x ADR).

**7. Seasonality is extreme at the Resort.** Its realized ADR ranges from €{m['resort_adr_jan']} in January to
€{m['resort_adr_aug']} in August. Jan-Aug 2017 revenue grew over Jan-Aug 2016 at both hotels (see `sql/04` yoy_jan_aug).

**8. Forecasting: simple wins.** Over the last {m['forecast_test_weeks']} weeks, "same week last year" forecast weekly
stays with {m['forecast_naive_mape']}% average error and beat a trend + seasonality regression. With only ~2 years
of history, the extra complexity did not pay off; the seasonal-naive benchmark is the one to use.

**9. Portugal: biggest market, least reliable.** Portuguese bookings are {m['portugal_revenue_share_pct']}% of
realized revenue but cancel {m['portugal_cancel_pct']}% of the time, largely driven by group and offline-agency
allotments.

## 3. Recommendations
1. **Grow the direct channel.** Member rates, best-price guarantee, retargeting. Moving 10% of OTA bookings to direct is
   worth about {eur(m['channel_shift10_gain'])} over the data period under the Excel assumptions (15% OTA commission,
   5% direct acquisition cost). Caveat: direct bookers are self-selected, so shifted guests may not fully adopt
   direct-channel behaviour. Treat this as an upper bound and test it.
2. **Risk-based deposits.** Score every new booking. Require a deposit (or prepaid rate) only for the top risk decile.
3. **Shorter free-cancellation windows for long lead times** and for group allotments.
4. **Overbook modestly** ({m['overbook_best_x']} rooms per 100) on high-demand nights, and review monthly.
5. **Encourage engagement** at booking (pre-arrival requests, upsells), which goes with fewer cancellations.

## 4. Data quality and judgment calls
| Issue | Rows | Handling |
|---|---:|---|
| Exact duplicate rows (no booking ID in the file) | {iss['exact_duplicate_rows_kept_and_flagged']:,} | **Kept** and flagged; sensitivity check below |
| Bookings with zero guests | {iss['removed_zero_guests']:,} | Removed |
| Negative price / price over €1,000 | {iss['removed_negative_adr'] + iss['removed_adr_outlier_over_1000']:,} | Removed |
| Undefined channel / segment | {iss['removed_undefined_channel']:,} | Removed |
| Missing country | {iss['country_missing_set_UNK']:,} | Set to "UNK" |
| 'CN' country code (not ISO-3) | - | Merged into CHN |

**Duplicate sensitivity:** without the flagged duplicates ({m['dedup_rows']:,} rows), the overall cancellation rate
is {m['dedup_cancel_rate_pct']}% instead of {m['cancel_rate_pct']}%, but the channel comparison holds (OTA
{m['dedup_ota_cancel_pct']}% vs Direct {m['dedup_direct_cancel_pct']}%). Absolute levels are uncertain; the
comparisons are robust.

**Deposit anomaly:** {m['non_refund_cancel_pct']}% of the {m['non_refund_bookings']:,} "Non Refund" bookings
were cancelled, which is the opposite of what the label suggests. They are concentrated in Portuguese group and
offline-agency bookings. Policy analysis therefore uses No-Deposit bookings only.

**Leakage:** reservation status, assigned room, booking changes and parking requests are excluded from the model.
0% of bookings with a parking request cancel, which suggests the field is filled at check-in.

## 5. Limitations
- Two hotels, one country, 2015-2017. Patterns may not generalise.
- Model probabilities run low in the test months (the cancellation rate rose to {100 * m['gbm_test_cancel_rate']:.0f}%),
  so ranking is reliable but the probabilities should be recalibrated on recent data before use.
- Revenue = ADR x nights: room revenue only (no food, extras or commissions in the data).
- Policy and channel numbers rest on stated assumptions. The Excel model lets you change them.
"""
    (C.OUTPUT_DIR / "INSIGHTS_REPORT.md").write_text(text, encoding="utf-8")


def main():
    metrics = {}
    for label, module in STEPS:
        t = time.time()
        print(f"\n{'=' * 70}\n{label}\n{'=' * 70}")
        metrics.update(module.run())
        print(f"[{label} done in {time.time() - t:.1f}s]")
    (C.OUTPUT_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2, default=str), encoding="utf-8")
    write_report(metrics)
    print(f"\nDone. Report: {C.OUTPUT_DIR / 'INSIGHTS_REPORT.md'}")
    print("Note: open excel/Hotel_Revenue_WhatIf.xlsx in Excel once and save it so the formula results are stored.")


if __name__ == "__main__":
    main()
